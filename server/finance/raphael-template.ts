type CategorySeed = {
  key: string;
  name: string;
  group: string;
  ownerType: "personal" | "business" | "both";
  essential: boolean;
};

function categories(
  group: string,
  ownerType: CategorySeed["ownerType"],
  essential: boolean,
  entries: Array<[string, string]>
): CategorySeed[] {
  return entries.map(([key, name]) => ({
    key,
    name,
    group,
    ownerType,
    essential,
  }));
}

