type GoalItemSeed = {
  seedKey: string;
  personOrGroup: string;
  name: string;
  estimatedCostCents: number;
  priority: "essential" | "important" | "optional";
  needsConfirmation?: boolean;
  notes?: string;
};

function item(
  personOrGroup: string,
  key: string,
  name: string,
  estimatedCostCents: number,
  priority: GoalItemSeed["priority"],
  extra: Pick<GoalItemSeed, "needsConfirmation" | "notes"> = {}
): GoalItemSeed {
  return {
    seedKey: `purchase-${personOrGroup.toLowerCase()}-${key}`,
    personOrGroup,
    name,
    estimatedCostCents,
    priority,
    ...extra,
  };
}

